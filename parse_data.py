mcq_list = []

for block in q_blocks:
    block = block.strip()
    if not block or block.startswith("PHẦN I:"):
        # Strip PHẦN I header if present
        block = re.sub(r'^PHẦN I:[^\n]*\n', '', block).strip()
    if not block:
        continue
    
    # Extract number, question, and options
    lines = [l.strip() for l in block.split('\n') if l.strip()]
    if not lines:
        continue
    
    # line 0 is question number e.g. "1."
    m_num = re.match(r'^(\d+)\.', lines[0])
    if not m_num:
        continue
    q_num = int(m_num.group(1))
    
