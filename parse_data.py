    q_text_lines = []
    opt_lines = []
    in_opts = False
    for line in lines[1:]:
        if re.match(r'^\*?[A-D]\.', line):
            in_opts = True
            opt_lines.append(line)
        else:
            if not in_opts:
                q_text_lines.append(line)
            else:
                # continuation of option
                if opt_lines:
                    opt_lines[-1] += " " + line
    
    q_text = " ".join(q_text_lines).strip()
    
    options = []
    correct_idx = -1
    for i, opt in enumerate(opt_lines):
        is_correct = opt.startswith('*')
        clean_opt = opt[1:].strip() if is_correct else opt.strip()
        # remove prefix A. B. C. D.
        opt_text = re.sub(r'^[A-D]\.\s*', '', clean_opt).strip()
        # Clean markdown links e.g. [Iosif Vissarionovich Stalin](...) -> Iosif Vissarionovich Stalin
